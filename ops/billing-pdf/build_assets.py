"""Build functions/_lib/pdf-assets.js: the images used in PDF copies of billing documents.

The logo, signature and seal come from functions/_lib/brand-assets.js (PNG with transparency)
and are flattened to JPEG on white, so pdf-lib embeds them without decoding (cheap on
Cloudflare's per-request CPU limit). The PDFs use the standard PDF fonts, so no fonts here.

  pip install pillow
  python3 ops/billing-pdf/build_assets.py
"""
import base64, io, os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
brand = open(os.path.join(ROOT, 'functions/_lib/brand-assets.js')).read()


def jpeg(name):
    b64 = re.search(r"export const %s = 'data:image/png;base64,([^']+)'" % name, brand).group(1)
    im = Image.open(io.BytesIO(base64.b64decode(b64))).convert('RGBA')
    bg = Image.new('RGB', im.size, (255, 255, 255)); bg.paste(im, mask=im.split()[3])
    b = io.BytesIO(); bg.save(b, 'JPEG', quality=90, optimize=True); return b.getvalue()


assets = [('LOGO_JPG', jpeg('LOGO')), ('SIGNATURE_JPG', jpeg('SIGNATURE')), ('SEAL_JPG', jpeg('SEAL'))]
head = ("/**\n * Images for PDF copies of issued documents (see billing-pdf.js). Generated by\n"
        " * ops/billing-pdf/build_assets.py - do not edit by hand. JPEG on white so they embed\n"
        " * without decoding. The signature and seal are deliberately not website files.\n */\n")
with open(os.path.join(ROOT, 'functions/_lib/pdf-assets.js'), 'w') as out:
    out.write(head + ''.join("export const %s = '%s';\n" % (n, base64.b64encode(b).decode()) for n, b in assets))
for n, b in assets: print(n, len(b))
